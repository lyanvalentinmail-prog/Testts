const DRIVE = {
  folder: 'CategoriasCanvas',
  banner: 'Banners',
} as const;

type ZoneInput = Omit<CanvasZone, 'mode'> & { mode?: CanvasZone['mode'] };

const z = (zone: ZoneInput): CanvasZone => ({
  shape: 'rect',
  align: 'center',
  valign: 'middle',
  padding: 12,
  ...zone,
  mode: zone.mode ?? 'text',
});

const zi = (zone: ZoneInput): CanvasZone => ({
  shape: 'rect',
  ...zone,
  mode: zone.mode ?? 'both',
});

/** Parámetros de salida comunes. */
const outputParams = (width: number, height: number, formats?: string[]): ParamDef[] => [
  ...(formats && formats.length && formats.every((f) => f === 'svg' || f === 'png' || f === 'jpeg' || f === 'webp')
    ? [widthParam(width), heightParam(height), formatParam(formats), qualityParam()]
    : [widthParam(width), heightParam(height), formatParam(['png', 'jpeg', 'webp', 'svg']), qualityParam()]),
  downloadParam(),
];

/** Parámetros de salida para los canvas animados (solo SVG y PNG). */
const animatedParams = (width: number, height: number): ParamDef[] => [
  widthParam(width),
  heightParam(height),
  formatParam(['svg', 'png'], 'svg'),
  param('duration', {
    type: 'number',
    label: 'Duración',
    description: 'Duración del bucle de animación en segundos (solo SVG).',
    default: 1.2,
    example: 1.2,
    minimum: 0.2,
    maximum: 10,
    step: 0.1,
    widget: 'slider',
    group: 'Salida',
    advanced: true,
  }),
  downloadParam(),
];

